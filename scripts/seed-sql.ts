import { ANALYSIS_TYPES, TYPE_RULES } from "../src/lib/data/analysis-types.ts";
import { SIMULATION_TYPES } from "../src/lib/data/simulation-types.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;

export const BLOG_CATEGORIES = [
  ["research", "Research", "Findings and case studies from simulation projects."],
  ["methods", "Methods", "How to set up, run and analyse molecular dynamics simulations."],
  ["tools-software", "Tools and software", "GROMACS, force fields, plotting and analysis tools."],
  ["tutorials", "Tutorials", "Step-by-step guides written by the community."],
  ["news", "News", "Platform updates and announcements."],
] as const;

/** supabase/seed.sql, generated from src/lib/data/analysis-types.ts. Run `npm run db:seed` after editing it. */
export function buildSeed(): string {
  const types = ANALYSIS_TYPES.map((t, i) => {
    const rules = TYPE_RULES[t.slug];
    if (!rules) throw new Error(`no upload rules for analysis type "${t.slug}"`);
    const fileRules = { allowed: rules.allowed, required: rules.required, max_mb: rules.maxMb };
    return `  (${[
      q(t.slug), q(t.name), arr(t.aliases), q(t.summary), arr(t.intro), t.command ? q(t.command) : "null",
      t.tutorial ? q(t.tutorial) : "null", String(t.requiresStructure), json(rules.fieldSchema), json(fileRules), String((i + 1) * 10),
    ].join(", ")})`;
  }).join(",\n");

  const sims = SIMULATION_TYPES.map(
    (t, i) =>
      `  (${[q(t.slug), q(t.name), arr(t.aliases), q(t.summary), arr(t.intro), String(t.requiresStructure), String((i + 1) * 10)].join(", ")})`,
  ).join(",\n");

  const cats = BLOG_CATEGORIES.map(([slug, name, desc], i) => `  (${q(slug)}, ${q(name)}, ${q(desc)}, ${(i + 1) * 10})`).join(",\n");

  return `-- GENERATED by \`npm run db:seed\` from src/lib/data/analysis-types.ts. Do not edit by hand.
-- Safe to run more than once: rows are matched on slug and updated.

insert into public.analysis_types
  (slug, name, aliases, summary, intro, command, tutorial_slug, requires_structure, field_schema, file_rules, sort_order)
values
${types}
on conflict (slug) do update set
  name = excluded.name, aliases = excluded.aliases, summary = excluded.summary, intro = excluded.intro,
  command = excluded.command, tutorial_slug = excluded.tutorial_slug, requires_structure = excluded.requires_structure,
  field_schema = excluded.field_schema, file_rules = excluded.file_rules, sort_order = excluded.sort_order;

insert into public.simulation_types (slug, name, aliases, summary, intro, requires_structure, sort_order)
values
${sims}
on conflict (slug) do update set
  name = excluded.name, aliases = excluded.aliases, summary = excluded.summary, intro = excluded.intro,
  requires_structure = excluded.requires_structure, sort_order = excluded.sort_order;

insert into public.blog_categories (slug, name, description, sort_order) values
${cats}
on conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;
`;
}
